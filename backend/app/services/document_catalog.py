DOCUMENT_CATALOG = DOCUMENT_CATALOGUE


def resolve_document_type(code_or_alias: str) -> Optional[str]:
    """Resolve an incoming code or alias to its canonical statutory document code."""
    if not code_or_alias:
        return None
    raw = code_or_alias.strip()
    # Direct match on code
    if raw in DOCUMENT_CATALOGUE:
        return raw
    # Direct alias match
    if raw in DOCUMENT_TYPE_ALIASES:
        return DOCUMENT_TYPE_ALIASES[raw]
    # Case-insensitive alias match
    normalized = raw.upper()
    if normalized in DOCUMENT_CATALOGUE:
        return normalized
    for alias_key, canonical in DOCUMENT_TYPE_ALIASES.items():
        if alias_key.upper() == normalized:
            return canonical
    return None


def get_catalog_entry(code_or_alias: str) -> Optional[Dict[str, Any]]:
    """Retrieve catalog entry by canonical code or recognized alias."""
    canonical = resolve_document_type(code_or_alias)
    if canonical:
        return DOCUMENT_CATALOGUE.get(canonical)
    return None


def get_document_catalog() -> Dict[str, Dict[str, Any]]:
    """Return the complete master catalogue of statutory document types."""
    return DOCUMENT_CATALOGUE


def get_document_type(code_or_alias: str) -> Optional[Dict[str, Any]]:
    """Retrieve document metadata by canonical code or recognized alias."""
    return get_catalog_entry(code_or_alias)


def get_category_catalog() -> Dict[str, Dict[str, Any]]:
    """Return all statutory AICTE application categories."""
    return APPLICATION_CATEGORIES


def get_required_documents_for_category(category_code: str) -> List[str]:
    """Retrieve canonical required document codes for a given application category."""
    cat = APPLICATION_CATEGORIES.get(category_code)
    if not cat:
        return []
    return cat.get("required_document_types", [])


def get_regulatory_document_types(category_code: Optional[str] = None) -> List[Dict[str, Any]]:
    """Return regulatory document catalogue entries with full statutory metadata,

    optionally filtered by application category.
    """
    items = []
    for doc in DOCUMENT_CATALOGUE.values():
        if category_code:
            applicable = doc.get("applicable_categories", [])
            if category_code not in applicable:
                continue
        items.append(doc)
    return items
